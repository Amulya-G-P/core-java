class Television
{
   public static String getBrand()
   {
      System.out.println("getBrand() invoked");
      System.out.println("Sony");
      return "Sony";
   }

   public static int getScreenSize()
   {
      System.out.println("getScreenSize() invoked");
      System.out.println(55);
      return 55;
   }

   public static String getResolution()
   {
      System.out.println("getResolution() invoked");
      System.out.println("4K UHD");
      return "4K UHD";
   }

   public static String getDisplayType()
   {
      System.out.println("getDisplayType() invoked");
      System.out.println("LED");
      return "LED";
   }

   public static double getPrice()
   {
      System.out.println("getPrice() invoked");
      System.out.println(62999.00);
      return 62999.00;
   }
}

